inline bool in_module(uintptr_t address, size_t length, uintptr_t base, size_t size) {
    return address >= base && address - base <= size && length <= size - (address - base);
}

inline std::optional<uintptr_t> direct_call(const sdk::discovery::Memory& memory,
    uintptr_t address, uintptr_t module_base, size_t module_size) {
    std::array<uint8_t, 5> bytes{};
    int32_t displacement{};
    if (!in_module(address, bytes.size(), module_base, module_size) ||
        !memory.load(address, bytes) || bytes[0] != 0xe8) { return {}; }
    std::memcpy(&displacement, bytes.data() + 1, sizeof(displacement));
    const auto target = sdk::discovery::relative_address(address + bytes.size(), displacement);
    if (!target || !in_module(*target, 1, module_base, module_size) ||
        !memory.executable || !memory.executable(memory.context, *target, 1)) { return {}; }
    return target;
}

// Discovery only: neither a constructor nor a destructor is executed here.
// The caller must additionally prove the vtable's existing UE5.7 destructor
// contract and require a unique candidate before publishing these functions.
inline std::optional<uintptr_t> family_copy_vtable(const sdk::discovery::Memory& memory,
    uintptr_t entry, size_t unwind_size, uintptr_t module_base, size_t module_size) {
    if (unwind_size != family_copy_size || !in_module(entry, family_copy_size, module_base, module_size) ||
        !memory.executable || !memory.executable(memory.context, entry, family_copy_size) ||
        !code_matches(memory, entry, copy_entry) ||
        !code_matches(memory, entry + 0x1f, copy_arrays) ||
        !code_matches(memory, entry + 0x35, all_views) ||
        !code_matches(memory, entry + 0x42, targets) ||
        !code_matches(memory, entry + 0xaf, additional) ||
        !code_matches(memory, entry + 0x293, owned) ||
        !code_matches(memory, entry + 0x318, copy_tail)) { return {}; }

    std::array<uint8_t, 7> lea{};
    int32_t displacement{};
    if (!memory.load(entry + 0x18, lea) || lea[0] != 0x48 || lea[1] != 0x8d || lea[2] != 0x05) { return {}; }
    std::memcpy(&displacement, lea.data() + 3, sizeof(displacement));
    const auto table = sdk::discovery::relative_address(entry + 0x1f, displacement);
    if (!table || !in_module(*table, sizeof(uintptr_t), module_base, module_size)) { return {}; }

    const auto views = direct_call(memory, entry + 0x30, module_base, module_size);
    const auto all = direct_call(memory, entry + 0x3d, module_base, module_size);
    if (!views || views != all || !in_module(*views, pointer_array_copy_size, module_base, module_size) ||
        !code_matches(memory, *views, array_entry) ||
        !code_matches(memory, *views + 0x5a, array_copy) ||
        !code_matches(memory, *views + 0x6c, array_tail) ||
        !direct_call(memory, *views + 0x55, module_base, module_size) ||
        !direct_call(memory, *views + 0x67, module_base, module_size)) { return {}; }

    // All out-of-line members must stay executable and inside the owning image.
    for (const auto offset : {0x68u, 0x1deu, 0x1ecu, 0x258u, 0x279u, 0x305u, 0x313u}) {
        if (!direct_call(memory, entry + offset, module_base, module_size)) { return {}; }
    }
    return table;
}

