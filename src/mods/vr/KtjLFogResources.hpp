inline bool validate_code(const sdk::discovery::Memory& memory, uintptr_t base) {
    if (!sdk::ktjl::validated_image(memory, base)) { return false; }
    std::array<uint8_t, 512> bytes{};
    for (const auto& code : code_evidence) {
        if (code.bytes.empty() || code.bytes.size() > bytes.size() ||
            !memory.executable(memory.context, base + code.rva, code.bytes.size()) ||
            !memory.read(memory.context, base + code.rva, bytes.data(), code.bytes.size()) ||
            std::memcmp(bytes.data(), code.bytes.data(), code.bytes.size()) != 0) { return false; }
    }
    uintptr_t accessor{}, release{}, destructor{};
    return memory.load(base + pool_vtable_rva + 0x10, accessor) && accessor == base + get_desc_rva &&
        memory.load(base + pool_vtable_rva + 0x38, release) && release == base + 0x55AAE0 &&
        memory.load(base + view_vtable_rva, destructor) && destructor == base + 0x57836D0;
}

template<typename T, size_t N>
T field(const std::array<uint8_t, N>& bytes, size_t offset) {
    T value{};
    if (offset <= N && sizeof(T) <= N - offset) {
        std::memcpy(&value, bytes.data() + offset, sizeof(value));
    }
    return value;
}

struct alignas(16) Descriptor {
    std::array<uint8_t, 0x50> bytes{};
    template<typename T> T at(size_t offset) const { return field<T>(bytes, offset); }
};
static_assert(sizeof(Descriptor) == 0x50);

inline bool valid_volume(const Descriptor& d) {
    const auto x = d.at<int32_t>(0x14), y = d.at<int32_t>(0x18), z = d.at<int32_t>(0x1C);
    // The game's helper requests a non-array, single-mip PF_FloatRGBA volume.
    return x > 0 && x <= 2048 && y > 0 && y <= 2048 && z > 0 && z <= 2048 &&
        d.at<int32_t>(0x20) == 1 && d.at<uint8_t>(0x24) == 0 && d.at<uint8_t>(0x25) == 0 &&
        d.at<uint16_t>(0x26) == 1 && d.at<uint16_t>(0x28) == 1 &&
        d.at<uint32_t>(0x2C) == 10 && d.at<uint32_t>(0x34) == 0x40010009 &&
        d.at<uint8_t>(0x38) == 0 && d.at<uint8_t>(0x39) == 0;
}

inline bool equivalent(const Descriptor& a, const Descriptor& b) {
    // Ignore padding and DebugName; retain the complete allocation/clear flags.
    for (size_t i = 0; i < a.bytes.size(); ++i) {
        if ((i >= 0x2A && i < 0x2C) || (i >= 0x3A && i < 0x48) || i >= 0x4C) { continue; }
        if (a.bytes[i] != b.bytes[i]) { return false; }
    }
    return true;
}

struct Resource {
    uintptr_t address{}, target{}, shader{}, uav{};
    Descriptor descriptor{};
};

inline bool read_resource(const sdk::discovery::Memory& memory, uintptr_t base, uintptr_t address, Resource& out) {
    std::array<uint8_t, 0xF0> bytes{};
    if (!sdk::ktjl::pointer(address) || !memory.load(address, bytes) ||
        field<uintptr_t>(bytes, 0) != base + pool_vtable_rva ||
        field<int32_t>(bytes, 0x88) < 2 || field<uint8_t>(bytes, 0xE0) != 0 ||
        field<uintptr_t>(bytes, 0xE8) != base + pool_rva) { return false; }
    out.address = address;
    out.target = field<uintptr_t>(bytes, 8);
    out.shader = field<uintptr_t>(bytes, 0x10);
    out.uav = field<uintptr_t>(bytes, 0x18);
    std::memcpy(out.descriptor.bytes.data(), bytes.data() + 0x90, out.descriptor.bytes.size());
    return sdk::ktjl::pointer(out.target) && sdk::ktjl::pointer(out.shader) &&
        sdk::ktjl::pointer(out.uav) && valid_volume(out.descriptor);
}

