inline bool distinct_matching(const Resource& left, const Resource& right) {
    return right.address != left.address && right.target != left.target &&
        right.shader != left.shader && right.uav != left.uav &&
        equivalent(left.descriptor, right.descriptor);
}

inline Plan prepare(const sdk::discovery::Memory& memory, uintptr_t base, uintptr_t renderer, bool fog_enabled) {
    Plan p{};
    p.renderer = renderer;
    if (!fog_enabled) { p.decision = Decision::passthrough; return p; }
    if (!sdk::ktjl::pointer(renderer) || !memory.load(renderer + views_offset, p.views)) { return p; }
    if (p.views.count != 2) { p.decision = Decision::passthrough; return p; }
    if (!sdk::ktjl::pointer(p.views.data) || p.views.capacity < 2 || p.views.capacity > 16) { return p; }
    const auto right = p.views.data + view_stride;
    ViewPrefix a{}, b{};
    uintptr_t a_state_vtable{}, b_state_vtable{}, left_texture{}, right_texture{};
    Rect ra{}, rb{};
    if (!memory.load(p.views.data, a) || !memory.load(right, b) ||
        a.vtable != base + view_vtable_rva || b.vtable != a.vtable ||
        a.family != renderer + 0x10 || b.family != a.family ||
        !sdk::ktjl::pointer(a.state) || !sdk::ktjl::pointer(b.state) || a.state == b.state ||
        !memory.load(a.state, a_state_vtable) || !memory.load(b.state, b_state_vtable) ||
        a_state_vtable != base + sdk::ktjl::stereo::state_vtable_rva || b_state_vtable != a_state_vtable ||
        !memory.load(p.views.data + rect_offset, ra) || !memory.load(right + rect_offset, rb) ||
        !ra.valid() || !rb.valid() || ra.max_x - ra.min_x != rb.max_x - rb.min_x ||
        ra.max_y - ra.min_y != rb.max_y - rb.min_y ||
        !memory.load(p.views.data + fog_reference_offset, left_texture) ||
        !read_resource(memory, base, left_texture, p.left)) { return p; }
    p.right_slot = right + fog_reference_offset;
    if (!memory.load(p.right_slot, right_texture)) { return p; }
    Header again{};
    if (!memory.load(renderer + views_offset, again) || again != p.views) { return p; }
    if (right_texture == 0) { p.decision = Decision::allocate; return p; }
    Resource existing{};
    if (read_resource(memory, base, right_texture, existing) && distinct_matching(p.left, existing)) {
        p.decision = Decision::existing;
    }
    return p;
}

inline bool allocation_completed(const sdk::discovery::Memory& memory, uintptr_t base, const Plan& p) {
    Header views{};
    uintptr_t left{}, right{};
    Resource result{};
    return p.decision == Decision::allocate && memory.load(p.renderer + views_offset, views) && views == p.views &&
        memory.load(p.views.data + fog_reference_offset, left) && left == p.left.address &&
        memory.load(p.right_slot, right) && read_resource(memory, base, right, result) &&
        distinct_matching(p.left, result);
}

enum class Outcome { passthrough, existing, allocated, rejected };
template<typename Allocate>
Outcome ensure(const sdk::discovery::Memory& memory, uintptr_t base, uintptr_t renderer, bool fog_enabled, Allocate&& allocate) {
    const auto p = prepare(memory, base, renderer, fog_enabled);
    switch (p.decision) {
    case Decision::passthrough: return Outcome::passthrough;
    case Decision::existing: return Outcome::existing;
    case Decision::allocate:
        // Only the validated game allocator may write the TRefCountPtr. FViewInfo's
        // existing destructor releases it; no private cache or borrowed left ref.
        if (allocate(p) && allocation_completed(memory, base, p)) { return Outcome::allocated; }
        break;
    default: break;
    }
    return Outcome::rejected;
}
