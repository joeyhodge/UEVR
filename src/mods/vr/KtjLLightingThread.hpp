inline bool validate_code(const sdk::discovery::Memory& memory, uintptr_t base) {
    if (!sdk::ktjl::validated_image(memory, base)) { return false; }
    for (const auto& evidence : code_evidence) {
        std::array<uint8_t, 256> bytes{};
        if (!memory.executable || !memory.read || evidence.bytes.size() > bytes.size() ||
            !memory.executable(memory.context, base + evidence.rva, evidence.bytes.size()) ||
            !memory.read(memory.context, base + evidence.rva, bytes.data(), evidence.bytes.size()) ||
            std::memcmp(bytes.data(), evidence.bytes.data(), evidence.bytes.size()) != 0) { return false; }
    }
    return true;
}

inline bool select_serial(const sdk::discovery::Memory& memory, uintptr_t base,
                          const safetyhook::Context& context) {
    if ((context.rax & 0xFF) != 1 || !sdk::ktjl::pointer(context.rdi) ||
        context.rsi != context.rdi + fog::views_offset ||
        context.r13 != base + immediate_rva || !sdk::ktjl::pointer(context.rsp) ||
        context.rsp >= 0x0000800000000000ULL - return_stack_offset) { return false; }
    uintptr_t caller{};
    fog::Header views{};
    if (!memory.load(context.rsp + return_stack_offset, caller) || caller != base + caller_return_rva ||
        !memory.load(context.rsi, views) || views.count != 2) { return false; }
    const auto pair = cloud_output::read_pair(memory, base, views.data);
    return pair && pair->renderer == context.rdi && pair->views == views;
}

inline void use_serial(safetyhook::Context& context) {
    // Let the original store write the normal false decision. Do not clear a
    // queued task/fence, call the pass twice, or change any global CVar.
    context.rax &= ~uintptr_t{0xFF};
}

template<class Create>
auto prepare_hook(uintptr_t base, safetyhook::MidHookFn callback, Create&& create) {
    return create(reinterpret_cast<void*>(base + boundary_rva), callback, safetyhook::MidHook::StartDisabled);
}
