inline bool validate_code(const sdk::discovery::Memory& memory, uintptr_t base) {
    if (!fog::validate_code(memory, base)) { return false; }
    for (const auto& e : code_evidence) {
        std::array<uint8_t, 256> bytes{};
        if (e.bytes.size() > bytes.size() || !memory.executable(memory.context, base + e.rva, e.bytes.size()) ||
            !memory.read(memory.context, base + e.rva, bytes.data(), e.bytes.size()) ||
            std::memcmp(bytes.data(), e.bytes.data(), e.bytes.size()) != 0) { return false; }
    }
    uintptr_t destroy{};
    return memory.load(base + sdk::ktjl::stereo::state_vtable_rva, destroy) && destroy == base + 0x1986F94;
}

inline bool valid_descriptor(const fog::Descriptor& d) {
    // Same 2D, single-sample PF_FloatR11G11B10 descriptor as the game's producer.
    // FindFreeElement can add the transient allocation hint internally.
    for (size_t i = 0; i < 0x14; ++i) { if (d.bytes[i] != 0) { return false; } }
    const auto width = d.at<int32_t>(0x14);
    return width > 0 && width <= 16384 && d.at<int32_t>(0x18) == width && d.at<int32_t>(0x1C) == 0 &&
        d.at<int32_t>(0x20) == 1 && d.at<uint8_t>(0x24) == 0 && d.at<uint8_t>(0x25) == 0 &&
        d.at<uint16_t>(0x26) == 1 && d.at<uint16_t>(0x28) == 1 && d.at<uint32_t>(0x2C) == 26 &&
        (d.at<uint32_t>(0x30) & ~0x80000000u) == 0 && d.at<uint32_t>(0x34) == 0x10009 &&
        d.at<uint16_t>(0x38) == 0;
}

inline bool read_resource(const sdk::discovery::Memory& memory, uintptr_t base, uintptr_t address, fog::Resource& out) {
    std::array<uint8_t, 0xF0> bytes{};
    if (!sdk::ktjl::pointer(address) || !memory.load(address, bytes) ||
        fog::field<uintptr_t>(bytes, 0) != base + fog::pool_vtable_rva ||
        fog::field<int32_t>(bytes, 0x88) < 2 || fog::field<uint8_t>(bytes, 0xE0) != 0 ||
        fog::field<uintptr_t>(bytes, 0xE8) != base + fog::pool_rva) { return false; }
    out.address = address;
    out.target = fog::field<uintptr_t>(bytes, 8);
    out.shader = fog::field<uintptr_t>(bytes, 0x10);
    out.uav = fog::field<uintptr_t>(bytes, 0x18);
    std::memcpy(out.descriptor.bytes.data(), bytes.data() + 0x90, out.descriptor.bytes.size());
    return sdk::ktjl::pointer(out.target) && sdk::ktjl::pointer(out.shader) &&
        sdk::ktjl::pointer(out.uav) && valid_descriptor(out.descriptor);
}

inline bool distinct(const fog::Resource& left, const fog::Resource& right) {
    return right.address != left.address && right.target != left.target &&
        right.shader != left.shader && right.uav != left.uav;
}

struct Plan {
    fog::Decision decision{fog::Decision::reject};
    fog::Header views{};
    uintptr_t renderer{}, view{}, left_state{}, right_state{}, right_slot{}, previous_right{};
    fog::Resource left{};
};

inline Plan prepare(const sdk::discovery::Memory& memory, uintptr_t base,
                    uintptr_t renderer, uintptr_t view, bool enabled) {
    Plan p{};
    p.renderer = renderer; p.view = view;
    if (!enabled) { p.decision = fog::Decision::passthrough; return p; }
    if (!sdk::ktjl::pointer(renderer) || !memory.load(renderer + fog::views_offset, p.views)) { return p; }
    if (p.views.count != 2) { p.decision = fog::Decision::passthrough; return p; }
    if (!sdk::ktjl::pointer(p.views.data) || p.views.capacity < 2 || p.views.capacity > 16 ||
        (view != p.views.data && view != p.views.data + fog::view_stride)) { return p; }
    fog::ViewPrefix a{}, b{};
    uintptr_t av{}, bv{}, left_ref{};
    if (!memory.load(p.views.data, a) || !memory.load(p.views.data + fog::view_stride, b) ||
        a.vtable != base + fog::view_vtable_rva || b.vtable != a.vtable ||
        a.family != renderer + 0x10 || b.family != a.family ||
        !memory.load(p.views.data + state_offset, p.left_state) ||
        !memory.load(p.views.data + fog::view_stride + state_offset, p.right_state) ||
        !sdk::ktjl::pointer(p.left_state) || !sdk::ktjl::pointer(p.right_state) || p.left_state == p.right_state ||
        a.state != p.left_state || b.state != p.right_state ||
        !memory.load(p.left_state, av) || !memory.load(p.right_state, bv) ||
        av != base + sdk::ktjl::stereo::state_vtable_rva || bv != av ||
        !memory.load(p.left_state + sky_ao_offset, left_ref) || !cloud::read_resource(memory, base, left_ref, p.left)) { return p; }
    p.right_slot = p.right_state + sky_ao_offset;
    if (!memory.load(p.right_slot, p.previous_right)) { return p; }
    fog::Header again{};
    if (!memory.load(renderer + fog::views_offset, again) || again != p.views) { return p; }
    if (p.previous_right == 0) { p.decision = fog::Decision::allocate; return p; }
    fog::Resource right{};
    if (!cloud::read_resource(memory, base, p.previous_right, right) || !distinct(p.left, right)) { return p; }
    p.decision = fog::equivalent(p.left.descriptor, right.descriptor) ? fog::Decision::existing : fog::Decision::allocate;
    return p;
}

inline bool allocation_completed(const sdk::discovery::Memory& memory, uintptr_t base, const Plan& p) {
    const auto after = prepare(memory, base, p.renderer, p.view, true);
    return p.decision == fog::Decision::allocate && after.decision == fog::Decision::existing &&
        after.views == p.views && after.left_state == p.left_state && after.right_state == p.right_state &&
        after.right_slot == p.right_slot && after.left.address == p.left.address &&
        fog::equivalent(after.left.descriptor, p.left.descriptor);
}

template<typename Allocate>
fog::Outcome ensure(const sdk::discovery::Memory& memory, uintptr_t base,
                    uintptr_t renderer, uintptr_t view, bool enabled, Allocate&& allocate) {
    const auto p = prepare(memory, base, renderer, view, enabled);
    switch (p.decision) {
    case fog::Decision::passthrough: return fog::Outcome::passthrough;
    case fog::Decision::existing: return fog::Outcome::existing;
    case fog::Decision::allocate:
        // The engine pool replaces/releases its own ref on resolution changes;
        // FSceneViewState already destroys this slot. Never cache or alias an eye.
        if (allocate(p) && allocation_completed(memory, base, p)) { return fog::Outcome::allocated; }
        break;
    default: break;
    }
    return fog::Outcome::rejected;
}
