inline bool should_use_native_fix(std::wstring_view path, bool ue425, bool dx12, bool native_fix) {
    return ue425 && dx12 && native_fix && sdk::ktjl::matches_executable(path);
}

inline bool matches_family_layout(const sdk::detail::FamilyLayout& layout) {
    // Corroborate the independently observed layout; never publish offsets here.
    return layout.has_vtable == false && layout.views == 0 && layout.render_target == 0x18 &&
        layout.scene_interface == 0x20 && layout.frame_count == frame_number_offset;
}

