struct RuntimeEntry {
    uintptr_t image_base{};
    uint32_t begin{}, end{}, unwind{};
};

inline std::optional<uintptr_t> resolve(const sdk::discovery::Memory& memory, uintptr_t base,
    uintptr_t callback_return, const RuntimeEntry& function, const sdk::detail::FamilyLayout& layout) {
    if (!matches_family_layout(layout) || !sdk::ktjl::validated_image(memory, base) ||
        function.image_base != base || function.begin != entry_rva || function.end != end_rva ||
        function.unwind != unwind_rva || callback_return != base + callback_return_rva ||
        !memory.executable || !memory.executable(memory.context, base + entry_rva, end_rva - entry_rva)) {
        return std::nullopt;
    }
    uintptr_t method{};
    std::array<uint8_t, root_unwind.size()> unwind{};
    if (!memory.load(base + method_table_slot_rva, method) || method != base + entry_rva ||
        !memory.load(base + unwind_rva, unwind) || unwind != root_unwind ||
        !sdk::ktjl::matches_code(memory, base + entry_rva, entry_code) ||
        !sdk::ktjl::matches_code(memory, base + frame_loop_rva, frame_loop_code) ||
        !sdk::ktjl::matches_code(memory, base + create_rva, create_code) ||
        !sdk::ktjl::matches_code(memory, base + return_rva, return_code)) {
        return std::nullopt;
    }
    return base + entry_rva;
}
