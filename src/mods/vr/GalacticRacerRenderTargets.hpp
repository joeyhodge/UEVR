struct SlateOutputTransaction {
    uintptr_t stack{}, inputs{}, original{}, replacement{};
    bool active() const { return original != 0; }
    bool begin(uintptr_t s, uintptr_t in, uintptr_t old_texture, uintptr_t new_texture) {
        if (active() || !pointer(s) || !pointer(in) || !pointer(old_texture) ||
            !pointer(new_texture) || old_texture == new_texture) { return false; }
        *this = {s, in, old_texture, new_texture};
        return true;
    }
    bool complete(uintptr_t s, uintptr_t in, uintptr_t& output) {
        if (!active() || stack != s || inputs != in || output != replacement) { return false; }
        output = original;
        *this = {};
        return true;
    }
};

inline bool slate_join(const sdk::discovery::Memory& m, uintptr_t join, uintptr_t begin, uintptr_t end) {
    if (join < 0x4c2 || begin != join - 0x4c2 || end <= join + 0x10a || end - begin > 0x3000 ||
        !code_matches(m, begin, slate_entry_code, slate_entry_mask) ||
        !code_matches(m, begin + 0x1e5, slate_array_code, slate_array_mask) ||
        !code_matches(m, begin + 0x2b5, slate_inputs_code, slate_inputs_mask) ||
        !code_matches(m, join - 0x1a, slate_select_code, slate_select_mask) ||
        !code_matches(m, join, slate_hash_code, slate_hash_mask) ||
        !code_matches(m, join + 0xbe, slate_register_code, slate_register_mask) ||
        !code_matches(m, join, slate_registration_code, slate_registration_mask) ||
        !code_matches(m, join + slate_registration_code.size(), slate_restore_code, slate_restore_mask) ||
        !code_matches(m, begin + 0x1a6, slate_graph_code, slate_graph_mask)) { return false; }
    int32_t name_disp{}, graph_disp{};
    std::array<wchar_t, 19> name{};
    constexpr std::wstring_view expected = L"SlateOutputTexture";
    if (!m.load(join + 0xcf, name_disp) || !m.load(begin + 0x1b3, graph_disp)) { return false; }
    const auto name_address = sdk::discovery::relative_address(join + 0xd3, name_disp);
    const auto graph_ctor = sdk::discovery::relative_address(begin + 0x1b7, graph_disp);
    constexpr std::array<uint8_t, 6> args{0x49,0x89,0xd6,0x48,0x89,0xce};
    constexpr std::array<uint8_t, 6> args_mask{0xff,0xff,0xff,0xff,0xff,0xff};
    constexpr std::array<uint8_t, 7> store{0x4c,0x89,0xb6,0xc0,0,0,0};
    constexpr std::array<uint8_t, 7> store_mask{0xff,0xff,0xff,0xff,0xff,0xff,0xff};
    return name_address && graph_ctor && m.load(*name_address, name) &&
        std::wstring_view{name.data(), expected.size()} == expected && name.back() == 0 &&
        code_matches(m, *graph_ctor + 0x1d, args, args_mask) &&
        code_matches(m, *graph_ctor + 0x118, store, store_mask);
}

struct SlateFrame { uint32_t width{}, height{}; uintptr_t command_list{}; };
template<class IsObject>
std::optional<SlateFrame> slate_frame(const sdk::discovery::Memory& m, uintptr_t inputs,
    uintptr_t viewport_info, uintptr_t stack, IsObject&& object) {
    SlateInputs in{};
    uintptr_t command_list{};
    uint8_t composite{};
    std::array<uint8_t, 16> command_storage{};
    if (!pointer(inputs) || !pointer(stack) || !m.load(inputs, in) ||
        in.viewport_info != viewport_info || !object(in.renderer) || !object(in.window) ||
        !object(in.viewport_info) || !pointer(in.elements) ||
        !std::isfinite(in.scale) || in.scale <= 0 || in.scale > 8 ||
        in.min_x != 0 || in.min_y != 0 || in.max_x <= 0 || in.max_y <= 0 ||
        in.max_x > 16384 || in.max_y > 16384 ||
        !m.load(stack + 0x7c, composite) || composite != 1 ||
        !m.load(stack + 0x250, command_list) || !pointer(command_list) ||
        command_list == stack + 0x190 || command_list == inputs ||
        !m.load(command_list, command_storage)) { return {}; }
    return SlateFrame{static_cast<uint32_t>(in.max_x), static_cast<uint32_t>(in.max_y), command_list};
}
